import { apiRequest } from './http';

/** Сколько ждём «просыпания» сервера: бесплатный хостинг засыпает без запросов, старт ~30–60 с. */
const WAKE_TIMEOUT_MS = 90_000;

/**
 * Разбудить сервер на старте приложения, пока пользователь ещё не дошёл до формы входа.
 * Не бросает: недоступный сервер — обычная ситуация, приложение работает как гость.
 */
export async function wakeApi(): Promise<void> {
  try {
    await apiRequest('/api/health', { timeoutMs: WAKE_TIMEOUT_MS });
  } catch {
    // Сервер недоступен — формы покажут ошибку сами.
  }
}
